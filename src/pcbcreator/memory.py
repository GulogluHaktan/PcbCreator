"""Vector memory (Chroma) of past designs and library parts, used for RAG.

Policy: only designs that pass the linter are ever stored, so retrieval can never
feed a known-broken module back to the LLM as an example.

Embeddings are computed here and passed to Chroma explicitly, so the embedder is
swappable (offline hashing embedder by default; plug in a real model for production).
"""

from __future__ import annotations

import hashlib
import math
import re
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Protocol

import chromadb

from .library import Library
from .lint import Report
from .models import Module, PartDef


class Embedder(Protocol):
    name: str

    def embed(self, texts: list[str]) -> list[list[float]]: ...


class HashingEmbedder:
    """Deterministic, offline bag-of-words hashing embedder. Good enough to rank
    modules/parts by shared vocabulary; replace with a neural embedder later."""

    name = "hash"

    def __init__(self, dim: int = 384):
        self.dim = dim

    def embed(self, texts: list[str]) -> list[list[float]]:
        out = []
        for text in texts:
            vec = [0.0] * self.dim
            for tok in re.findall(r"[a-z0-9_+.]+", text.lower()):
                h = int.from_bytes(hashlib.blake2b(tok.encode(), digest_size=8).digest(), "big")
                vec[h % self.dim] += 1.0 if (h >> 63) & 1 else -1.0
            norm = math.sqrt(sum(v * v for v in vec)) or 1.0
            out.append([v / norm for v in vec])
        return out


class MiniLMEmbedder:
    """Neural sentence embedder (all-MiniLM-L6-v2, ONNX, runs locally on CPU; the ~80 MB model is
    downloaded once by Chroma). Understands that "LDO" and "low dropout regulator" are related."""

    name = "minilm"

    def __init__(self) -> None:
        from chromadb.utils.embedding_functions import DefaultEmbeddingFunction

        self._f = DefaultEmbeddingFunction()

    def embed(self, texts: list[str]) -> list[list[float]]:
        return [list(map(float, v)) for v in self._f(texts)]


def make_embedder(name: str) -> Embedder:
    return MiniLMEmbedder() if name == "minilm" else HashingEmbedder()


@dataclass
class ModuleHit:
    module: Module
    distance: float


@dataclass
class BlockHit:
    kind: str
    instruction: str
    patch_json: str
    origin: str
    source: str
    distance: float


@dataclass
class PartHit:
    part_id: str
    distance: float
    part: PartDef | None = None  # present for small libraries; big ones are resolved via Library.get


def module_text(m: Module) -> str:
    parts = " ".join(sorted({i.part for i in m.parts}))
    ports = " ".join(f"{p.net}:{p.direction}" + (f":{p.protocol}" if p.protocol else "") for p in m.ports)
    return f"{m.name}. {m.description}. parts: {parts}. ports: {ports}"


class DesignMemory:
    def __init__(self, path: str, embedder: Embedder | None = None):
        self.embedder = embedder or HashingEmbedder()
        self.client = chromadb.PersistentClient(path=path)
        # collections are per-embedder: vectors from different embedders must never be mixed
        suffix = self.embedder.name
        self.modules = self.client.get_or_create_collection(f"modules_{suffix}")
        self.parts = self.client.get_or_create_collection(f"parts_{suffix}")
        self.datasheets = self.client.get_or_create_collection(f"datasheets_{suffix}")
        self.blocks = self.client.get_or_create_collection(f"blocks_{suffix}")

    # --- modules ---------------------------------------------------------
    def add_module(self, module: Module, report: Report, origin: str = "llm") -> str:
        """origin: "llm" (generated by the pipeline) or "human" (hand-written/seeded)."""
        if not report.passed:
            raise ValueError(f"refusing to store module '{module.name}': it fails lint "
                             f"({len(report.errors)} errors)")
        spec = module.model_dump_json()
        mid = hashlib.sha1(spec.encode()).hexdigest()
        text = module_text(module)
        self.modules.upsert(
            ids=[mid], documents=[text], embeddings=self.embedder.embed([text]),
            metadatas=[{"name": module.name, "spec": spec, "warnings": len(report.warnings), "origin": origin,
                        "created": datetime.now(timezone.utc).isoformat()}],
        )
        return mid

    def search_modules(self, query: str, n: int = 3, exclude_origins: list[str] | None = None) -> list[ModuleHit]:
        count = self.modules.count()
        if count == 0:
            return []
        where = {"origin": {"$nin": exclude_origins}} if exclude_origins else None
        res = self.modules.query(query_embeddings=self.embedder.embed([query]), n_results=min(n, count), where=where)
        return [ModuleHit(Module.model_validate_json(meta["spec"]), dist)
                for meta, dist in zip(res["metadatas"][0], res["distances"][0])]

    # --- blocks: reusable connection patterns (an LED with its resistor, an IC with its decoupling...) ---
    def add_block(self, kind: str, instruction: str, patch_json: str, parts: list[str], origin: str,
                  source: str = "") -> str:
        """Store one accepted block. Callers must only pass blocks of designs that passed every gate."""
        bid = hashlib.sha1((kind + patch_json).encode()).hexdigest()
        text = f"{kind}. {instruction}. parts: {' '.join(sorted(set(parts)))}"
        self.blocks.upsert(ids=[bid], documents=[text], embeddings=self.embedder.embed([text]),
                           metadatas=[{"kind": kind, "instruction": instruction, "patch": patch_json,
                                       "origin": origin, "source": source,
                                       "created": datetime.now(timezone.utc).isoformat()}])
        return bid

    def search_blocks(self, query: str, n: int = 2, exclude_origins: list[str] | None = None) -> list[BlockHit]:
        count = self.blocks.count()
        if count == 0:
            return []
        where = {"origin": {"$nin": exclude_origins}} if exclude_origins else None
        res = self.blocks.query(query_embeddings=self.embedder.embed([query]), n_results=min(n, count), where=where)
        return [BlockHit(m["kind"], m["instruction"], m["patch"], m["origin"], m["source"], d)
                for m, d in zip(res["metadatas"][0], res["distances"][0])]

    # --- parts -----------------------------------------------------------
    def index_parts(self, lib: Library) -> None:
        parts = lib.all()
        texts = [f"{p.id} {p.category} {p.description} " + " ".join(pin.name for pin in p.pins) for p in parts]
        self.parts.upsert(ids=[p.id for p in parts], documents=texts, embeddings=self.embedder.embed(texts),
                          metadatas=[{"spec": p.model_dump_json()} for p in parts])

    def index_library(self, lib: Library, batch: int = 2000) -> int:
        """Index every part of a (possibly huge) library. Only id + searchable text are stored;
        full pin data is resolved from the library on demand."""
        parts = lib.all()
        for i in range(0, len(parts), batch):
            chunk = parts[i:i + batch]
            texts = [f"{p.id} {p.category} {p.description} " + " ".join(pin.name for pin in p.pins[:40]) for p in chunk]
            self.parts.upsert(ids=[p.id for p in chunk], documents=texts, embeddings=self.embedder.embed(texts),
                              metadatas=[{"category": p.category, "footprint": p.footprint} for p in chunk])
        return len(parts)

    def search_parts(self, query: str, n: int = 8, category: str | None = None) -> list[PartHit]:
        count = self.parts.count()
        if count == 0:
            return []
        where = {"category": category} if category else None
        res = self.parts.query(query_embeddings=self.embedder.embed([query]), n_results=min(n, count), where=where)
        hits = []
        for pid, meta, dist in zip(res["ids"][0], res["metadatas"][0], res["distances"][0]):
            spec = meta.get("spec")
            hits.append(PartHit(pid, dist, PartDef.model_validate_json(spec) if spec else None))
        return hits
